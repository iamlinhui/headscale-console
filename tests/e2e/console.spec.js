async function fillCaptcha(page, value = 'TEST') {
  await expect(page.getByTestId('captcha-image')).toBeVisible()
  await expect(page.getByTestId('login-captcha').locator('input')).toBeEnabled()
  await page.getByTestId('login-captcha').locator('input').fill(value)
}
async function login(page) {
  await page.goto('/')
  await page.getByTestId('login-username').locator('input').fill('ui-test')
  await page.getByTestId('login-password').locator('input').fill('E2E-fixture-only!')
  await fillCaptcha(page)
  await page.getByTestId('login-submit').click()
  await expect(page.getByRole('heading', { name:'概览', exact:true })).toBeVisible()
}
async function nav(page, label) { await page.locator('.sidebar .n-menu-item-content-header').filter({hasText:new RegExp(`^${label}$`)}).click() }
