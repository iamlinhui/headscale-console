test('GIF 验证码换图、错误拦截与失败后刷新', async ({page}) => {
  await page.goto('/')
  await fillCaptcha(page, 'WRONG')
  const first = await page.getByTestId('captcha-image').getAttribute('src')
  expect(first).toMatch(/^data:image\/gif;base64,/)
  const refreshed = page.waitForResponse(r => r.url().endsWith('/api/auth/captcha') && r.request().method()==='POST')
  await page.getByTestId('captcha-refresh').click()
  const challenge = await (await refreshed).json()
  expect(challenge.captchaId).toMatch(/^[a-f0-9]{64}$/)
  await expect(page.getByTestId('login-captcha').locator('input')).toHaveValue('')
  await fillCaptcha(page, 'WRONG')
  expect(await page.getByTestId('captcha-image').getAttribute('src')).toMatch(/^data:image\/gif;base64,/)
  // Fixed TEST fixture can legitimately render identical bytes; random challenge ID still rotates.
  await page.getByTestId('login-username').locator('input').fill('ui-test')
  await page.getByTestId('login-password').locator('input').fill('E2E-fixture-only!')
  await page.getByTestId('login-submit').click()
  await expect(page.getByRole('alert')).toContainText('验证码错误或已失效')
  await expect(page.getByTestId('login-captcha').locator('input')).toHaveValue('')
  await fillCaptcha(page)
  await page.getByTestId('login-submit').click()
  await expect(page.getByRole('heading', {name:'概览',exact:true})).toBeVisible()
})
